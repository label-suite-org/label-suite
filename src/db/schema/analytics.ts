// Imported evidence remains immutable; this records the human disposition separately.
export const analytics_duplicate_reviews = schema.table("analytics_duplicate_reviews", {
  id: text("id").primaryKey(),
  org_id: text("org_id").notNull().references(() => orgs.id),
  candidate_key: text("candidate_key").notNull(),
  disposition: text("disposition").notNull(),
  reason: text("reason"),
  reviewed_by: text("reviewed_by").notNull(),
  reviewed_at: timestamp("reviewed_at", { withTimezone: true }).notNull(),
}, (table) => [
  uniqueIndex("analytics_duplicate_reviews_org_candidate_unique").on(table.org_id, table.candidate_key),
  index("analytics_duplicate_reviews_org_reviewed_at_idx").on(table.org_id, table.reviewed_at),
]);
